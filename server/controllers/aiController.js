exports.parseTask = (req, res) => {
    const { prompt } = req.body;
    res.json({
        parsedTask: {
            title: "Task based on: " + prompt.substring(0, 15) + "...",
            description: "Automatically generated by dummy AI",
            category: "work",
            priority: "medium",
            task_date: new Date().toISOString().split('T')[0],
            start_time: "10:00",
            end_time: "11:00"
        }
    });
};